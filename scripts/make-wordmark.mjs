// One-off build script: converts the word "Style" set in Allura (Google Fonts, OFL) and
// "BY DAWN" set in Libre Caslon Display capitals (0.22em tracking) into SVG paths.
// Writes components/Wordmark.tsx and lib/monogram.ts (the "S" used for icons).
// Allura is never loaded at runtime. Run: node scripts/make-wordmark.mjs
import fs from 'node:fs';
import opentype from 'opentype.js';

const load = (p) => opentype.parse(fs.readFileSync(p).buffer.slice(0));
const allura = load('scripts/fonts/Allura-Regular.ttf');
const caslon = load('scripts/fonts/LibreCaslonDisplay-Regular.ttf');

const r = (n) => Math.round(n * 10) / 10;
function pathData(p) {
  return p.commands
    .map((c) => {
      switch (c.type) {
        case 'M': return `M${r(c.x)} ${r(c.y)}`;
        case 'L': return `L${r(c.x)} ${r(c.y)}`;
        case 'C': return `C${r(c.x1)} ${r(c.y1)} ${r(c.x2)} ${r(c.y2)} ${r(c.x)} ${r(c.y)}`;
        case 'Q': return `Q${r(c.x1)} ${r(c.y1)} ${r(c.x)} ${r(c.y)}`;
        case 'Z': return 'Z';
        default: return '';
      }
    })
    .join('');
}

// "Style" in Allura
const STYLE_SIZE = 200;
const style = allura.getPath('Style', 0, 0, STYLE_SIZE, { kerning: true, features: { liga: true, calt: true } });
const sb = style.getBoundingBox();

// "BY DAWN" in Libre Caslon Display, tracked 0.22em, set beneath the "le" like the shop sign
const BY_SIZE = 26;
const tracking = 0.22 * BY_SIZE;
let x = 0;
const glyphPaths = [];
for (const ch of 'BY DAWN') {
  const g = caslon.charToGlyph(ch);
  glyphPaths.push(g.getPath(x, 0, BY_SIZE));
  x += (g.advanceWidth / caslon.unitsPerEm) * BY_SIZE + tracking;
}
const byWidth = x - tracking;
const byRight = sb.x2 - 6;
const byLeft = byRight - byWidth;
const byBaseline = 46; // below the Style baseline, clear of the y descender on the left
const byPath = new opentype.Path();
for (const gp of glyphPaths) {
  for (const c of gp.commands) {
    const t = { ...c };
    for (const k of ['x', 'x1', 'x2']) if (k in t) t[k] += byLeft;
    for (const k of ['y', 'y1', 'y2']) if (k in t) t[k] += byBaseline;
    byPath.commands.push(t);
  }
}
const bb = byPath.getBoundingBox();
const minX = Math.min(sb.x1, bb.x1) - 4;
const minY = Math.min(sb.y1, bb.y1) - 4;
const maxX = Math.max(sb.x2, bb.x2) + 4;
const maxY = Math.max(sb.y2, bb.y2) + 4;
const vb = `${r(minX)} ${r(minY)} ${r(maxX - minX)} ${r(maxY - minY)}`;

const tsx = `// GENERATED by scripts/make-wordmark.mjs. Do not edit by hand.
// "Style" set in Allura, "BY DAWN" in Libre Caslon Display capitals at 0.22em tracking, as paths.
// DRAFT: swap for her real logo file when she sends it
type Props = { className?: string; title?: string };

export const WORDMARK_VIEWBOX = '${vb}';

export function Wordmark({ className, title = 'Style by Dawn' }: Props) {
  return (
    <svg viewBox={WORDMARK_VIEWBOX} className={className} role="img" aria-label={title} fill="currentColor">
      <path d="${pathData(style)}" />
      <path d="${pathData(byPath)}" />
    </svg>
  );
}

export const WORDMARK_STYLE_PATH = '${pathData(style)}';
export const WORDMARK_BY_PATH = '${pathData(byPath)}';
`;
fs.writeFileSync('components/Wordmark.tsx', tsx);

// Monogram: the script "S" alone
const sPath = allura.getPath('S', 0, 0, 200);
const sbx = sPath.getBoundingBox();
const mono = `// GENERATED by scripts/make-wordmark.mjs. The script "S" from the wordmark, used for icons.
export const MONOGRAM_PATH = '${pathData(sPath)}';
export const MONOGRAM_BOX = { x: ${r(sbx.x1)}, y: ${r(sbx.y1)}, w: ${r(sbx.x2 - sbx.x1)}, h: ${r(sbx.y2 - sbx.y1)} };
`;
fs.writeFileSync('lib/monogram.ts', mono);
console.log('viewBox', vb, 'style bbox', sb, 'by bbox', bb, 'S box', sbx);
