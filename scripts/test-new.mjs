// /new filters and lightbox. Usage: node scripts/test-new.mjs [base]
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const base = process.argv[2] || 'http://localhost:3000';
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
let ok = true;
const assert = (c, m) => { console.log((c ? '  ok  ' : '  FAIL ') + m); if (!c) ok = false; };
await p.goto(base + '/new', { waitUntil: 'networkidle' });
assert((await p.locator('ul.columns-2 > li').count()) === 19, 'All shows 19 pieces');
await p.getByRole('button', { name: 'Cozy and gifts' }).click();
const cozy = await p.locator('ul.columns-2 > li').count();
assert(cozy === 3, `Cozy and gifts filters client-side (${cozy})`);
assert(p.url().endsWith('/new'), 'no navigation on filter');
await p.getByRole('button', { name: /Open a larger photo: Merry/ }).click();
const dlg = p.locator('dialog[open]');
await dlg.waitFor();
const t1 = await dlg.getAttribute('aria-label');
await p.keyboard.press('ArrowRight');
const t2 = await dlg.getAttribute('aria-label');
assert(t1 !== t2, `arrow key moves (${t1} -> ${t2})`);
await p.keyboard.press('Escape');
await p.waitForTimeout(200);
assert((await p.locator('dialog[open]').count()) === 0, 'Esc closes the lightbox');
assert(/Open a larger photo/.test(await p.evaluate(() => document.activeElement?.getAttribute('aria-label') || '')), 'focus returns to the photo');
await b.close();
console.log(ok ? '/new: all passed' : '/new: FAILURES');
process.exit(ok ? 0 : 1);
